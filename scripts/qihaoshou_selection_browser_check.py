"""Browser acceptance of source selection, preview and writing; local HTTP provider fixture only."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
out=Path(__file__).resolve().parents[1]/'output'/'qihaoshou-selection-qa'
out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(channel='msedge',headless=True)
 page=browser.new_page(viewport={'width':1600,'height':1100})
 errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
 page.on('dialog',lambda dialog:dialog.accept())
 page.goto('http://127.0.0.1:8894/qihaoshou')
 page.locator('#q-email').fill('writer-test@example.com');page.locator('#q-password').fill('writer-test-123');page.locator('#q-login-form button').click()
 expect(page.locator('#q-studio')).to_be_visible()
 expect(page.locator('#q-style-buttons button')).to_have_count(7)
 page.locator('#q-style-buttons button[data-style="tech"]').click()
 expect(page.locator('#q-style')).to_have_value('tech')
 expect(page.locator('#q-style-description')).to_contain_text('未实测')
 page.locator('#q-theme').select_option('purple');page.locator('#q-theme-preview').click()
 expect(page.locator('#q-preview-dialog')).to_be_visible()
 expect(page.frame_locator('#q-theme-preview-frame').locator('h1')).to_contain_text('先把一件事说明白')
 page.locator('#q-preview-close').click()
 page.locator('#q-tab-ai').click();page.locator('#q-topic-direction').fill('创作者写作')
 page.locator('#q-topics-refresh').click()
 expect(page.locator('#q-topic-cards article')).to_have_count(3,timeout=20000)
 expect(page.locator('#q-topic-cards a').first).to_have_attribute('href','https://example.com/news')
 page.locator('#q-topic-cards button').first.click()
 expect(page.locator('#q-topic')).to_have_value('把记录写成文章0')
 expect(page.locator('#q-angle')).to_have_value('从真实素材开始')
 page.locator('#q-save').click();expect(page.locator('#q-status')).to_contain_text('草稿已保存')
 sid=page.locator('#q-history').input_value()
 data=page.request.get('http://127.0.0.1:8894/api/qihaoshou/sessions/'+sid).json()
 assert data['mode']=='ai' and 'example.com' in data['source_notes'] and data['style']=='tech'
 page.screenshot(path=str(out/'desktop-ai.png'),full_page=True)
 page.locator('#q-tab-hot').click();page.locator('#q-hot-category').select_option('科技');page.locator('#q-hot-refresh').click()
 expect(page.locator('#q-hot-cards article')).to_have_count(1,timeout=15000)
 page.locator('#q-hot-cards button').click();expect(page.locator('#q-topic')).to_have_value('近期创作工具资讯样本')
 page.locator('#q-tab-custom').click();page.locator('#q-topic').fill('把每天的记录变成文章');page.locator('#q-angle').fill('解释记录为什么有用')
 page.locator('#q-tab-rewrite').click();expect(page.locator('#q-reference')).to_be_visible()
 page.locator('#q-reference').fill('每天记录十分钟，把当天发生的具体事情记下来。整理时先核对事实，再提炼一个清楚的问题。工具只是辅助，不替代真实素材。')
 page.locator('#q-generate').click();expect(page.locator('#q-status')).to_contain_text('文章已生成并保存',timeout=20000)
 expect(page.frame_locator('#q-editor').locator('h1')).to_have_text('从一段记录开始写作')
 page.locator('#q-layout').click();expect(page.locator('#q-status')).to_contain_text('主题已应用')
 page.locator('#q-tab-ai').click()
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth+2')
 page.screenshot(path=str(out/'mobile.png'),full_page=True)
 assert not errors,errors
 print('PASS seven style buttons, theme preview, paid topics, source links, draft persistence, dated news, custom/rewrite generation, theme application, mobile overflow')
 browser.close()
